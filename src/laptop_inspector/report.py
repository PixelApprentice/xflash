"""Local JSON/HTML report rendering."""
from __future__ import annotations

import html
import json
from typing import Any


def to_json(report: dict[str, Any]) -> str:
    return json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def to_html(report: dict[str, Any]) -> str:
    def esc(value: Any) -> str:
        return html.escape(str(value), quote=True)

    cards = []
    for finding in report.get("findings", []):
        evidence = "<pre>" + esc(json.dumps(finding.get("evidence", {}), indent=2, ensure_ascii=False)) + "</pre>"
        cards.append(
            '<section class="finding ' + esc(finding.get("severity", "info")) + '">'
            + '<p class="meta">' + esc(finding.get("severity", "").upper()) + ' · ' + esc(finding.get("component", "")) + ' · ' + esc(finding.get("code", "")) + '</p>'
            + '<h2>' + esc(finding.get("title", "Finding")) + '</h2>'
            + '<p>' + esc(finding.get("details", "")) + '</p>'
            + '<h3>Evidence</h3>' + evidence
            + '<h3>Recommended next action</h3><p>' + esc(finding.get("recommended_action", "")) + '</p>'
            + '<p class="meta">Confidence: ' + esc(finding.get("confidence", "unknown")) + ' · Source: ' + esc(finding.get("source") or "not supplied") + '</p>'
            + '</section>'
        )
    if not cards:
        cards.append('<p>No anomaly findings were generated by the evaluated checks. This does not mean every component passed.</p>')

    coverage = report.get("coverage", {})
    coverage_rows = []
    for check_name, status in sorted(coverage.items()):
        status_cls = esc(status.lower())
        coverage_rows.append(
            '<tr><td><code>' + esc(check_name) + '</code></td>'
            + '<td><span class="badge ' + status_cls + '">' + esc(status.upper()) + '</span></td></tr>'
        )
    coverage_section = ""
    if coverage_rows:
        coverage_section = (
            '<h2>Test coverage</h2>'
            + '<table class="coverage-table"><thead><tr><th>Diagnostic Check</th><th>Status</th></tr></thead>'
            + '<tbody>' + "".join(coverage_rows) + '</tbody></table>'
        )

    limitations = "".join("<li>" + esc(x) + "</li>" for x in report.get("limitations", []))
    return """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Laptop inspection report</title><style>
body{font:16px/1.6 "Lora",Georgia,serif;max-width:960px;margin:2rem auto;padding:0 1.25rem;color:#141413;background:#faf9f5}
h1,h2,h3{font-family:"Poppins",Arial,sans-serif;margin-bottom:.3rem;letter-spacing:-0.02em}
.muted,.meta{color:#5e5b52;font-size:.9rem}
.finding{background:#fff;border:1px solid #e8e6dc;border-left:5px solid #878479;border-radius:8px;padding:1.1rem;margin:1rem 0;overflow-wrap:anywhere;box-shadow:0 1px 3px rgba(20,20,19,0.04)}
.finding.warning{border-left-color:#c97f26}.finding.high{border-left-color:#d97757}.finding.critical{border-left-color:#c84b31}.finding.inconclusive{border-left-color:#878479}
pre{white-space:pre-wrap;background:#f3f1ea;padding:.75rem;border-radius:6px;font-family:ui-monospace,"JetBrains Mono",monospace;font-size:0.86rem;border:1px solid #e8e6dc}
li{margin:.35rem 0}
.coverage-table{width:100%;border-collapse:collapse;margin:1rem 0;background:#fff;border-radius:6px;overflow:hidden;border:1px solid #e8e6dc}
.coverage-table th,.coverage-table td{border:1px solid #e8e6dc;padding:.6rem .85rem;text-align:left}
.coverage-table th{background:#f3f1ea;font-family:"Poppins",Arial,sans-serif;font-size:.82rem;font-weight:600;color:#5e5b52}
.badge{display:inline-block;padding:.2rem .55rem;border-radius:9999px;font-size:.75rem;font-weight:700;text-transform:uppercase;font-family:"Poppins",Arial,sans-serif;letter-spacing:.03em}
.badge.passed{background:#f5f7f1;color:#3b522c;border:1px solid #dbe4cd}.badge.warning{background:#fcf7ef;color:#78470e;border:1px solid #f6e2c2}.badge.high{background:#fdf5f1;color:#7e2b14;border:1px solid #f6d8cc}.badge.critical{background:#c84b31;color:#fff}.badge.inconclusive{background:#f3f1ea;color:#5e5b52;border:1px solid #e8e6dc}.badge.skipped,.badge.not_run{background:#f3f1ea;color:#878479}
@media print{body{margin:0;max-width:none;background:#fff;color:#000}.finding{break-inside:avoid;border:1px solid #ccc}}
</style></head><body>
<h1>Laptop inspection report</h1><p class="muted">Inspection ID: """ + esc(report.get("inspection_id") or "not supplied") + """ · Generated by """ + esc(report.get("generated_by", "unknown")) + """</p>
<p><strong>Risk state:</strong> """ + esc(report.get("risk_state", "unknown")) + """ · <strong>Findings:</strong> """ + esc(report.get("finding_count", 0)) + """</p>
""" + coverage_section + """
<h2>Findings</h2>""" + "\n".join(cards) + "<h2>Limitations</h2><ul>" + limitations + "</ul></body></html>\n"
